"""A matplotlib style sheet from the figure's style tokens, so plots arrive ready to place.

Plots exported with it need no restyling in Inkscape and keep their text editable:

* ``svg.fonttype: none`` — text is written as real ``<text>``, not outlined glyphs;
* the figure's font, ink colour, line weights and series colours (``plot.series``);
* no top/right spines, transparent background, stable element ids (``svg.hashsalt``).

    python -m inkscape_mcp.mplstyle [STYLE] [--font Calibri] [--size 8] > figures/figure.mplstyle

STYLE is a preset ("nature", "reference") or a style.json (default: the built-in tokens).
In the plotting script::

    plt.style.use("figures/figure.mplstyle")
    fig.savefig("plot.svg")   # the svg backend, not cairo, so text stays text

Pasted into the figure, such a plot is matched by its matplotlib ids (``line2d_3``) when
``inkscape_live`` ``transplant`` swaps it in for an older version.
"""

from __future__ import annotations

import argparse
import sys
from typing import Any

from .figure_kit import load_style


def _hex(colour: str) -> str:
    return colour.lstrip("#")


def to_mplstyle(style: dict[str, Any], font: str | None = None, size_pt: float = 8.0) -> str:
    """The style sheet text for `style` (load_style output)."""
    plot = style.get("plot", {})
    ink = _hex(plot.get("axis") or style.get("ink", "#333333"))  # '#' starts a comment in .mplstyle
    family = font or style.get("font", {}).get("label", "sans-serif")
    series = plot.get("series") or [style["species"]["rna"]["color"]]
    lw = style.get("stroke", {})
    rows = {
        # Text stays text, ids stay stable between exports.
        "svg.fonttype": "none",
        "svg.hashsalt": "inkscape-mcp",
        "font.family": family,
        "font.size": f"{size_pt:g}",
        "axes.titlesize": f"{size_pt:g}",
        "axes.labelsize": f"{size_pt:g}",
        "xtick.labelsize": f"{size_pt:g}",
        "ytick.labelsize": f"{size_pt:g}",
        "legend.fontsize": f"{size_pt:g}",
        "mathtext.fontset": "custom",
        "mathtext.it": f"{family}:italic",
        "mathtext.rm": family,
        # Ink and weights.
        "text.color": ink,
        "axes.labelcolor": ink,
        "axes.edgecolor": ink,
        "xtick.color": ink,
        "ytick.color": ink,
        "axes.linewidth": f"{lw.get('hairline', 0.35) * 2:g}",
        "xtick.major.width": f"{lw.get('hairline', 0.35) * 2:g}",
        "ytick.major.width": f"{lw.get('hairline', 0.35) * 2:g}",
        "xtick.major.size": "2",
        "ytick.major.size": "2",
        "lines.linewidth": f"{lw.get('strand', 0.9) * 1.25:g}",
        "axes.prop_cycle": "cycler('color', [" + ", ".join(f"'{_hex(c)}'" for c in series) + "])",
        # Clean, flat, editorial.
        "axes.spines.top": "False",
        "axes.spines.right": "False",
        "axes.grid": "False",
        "legend.frameon": "False",
        "figure.facecolor": "none",
        "axes.facecolor": "none",
        "savefig.transparent": "True",
        "savefig.bbox": "tight",
        "savefig.format": "svg",
    }
    lines = ["# Generated by python -m inkscape_mcp.mplstyle from the figure's style tokens."]
    lines += [f"{k}: {v}" for k, v in rows.items()]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="python -m inkscape_mcp.mplstyle", description=__doc__.split("\n\n")[0])
    ap.add_argument("style", nargs="?", help="preset name or style.json (default: built-in tokens)")
    ap.add_argument("--font", help="font family (default: the style's label font)")
    ap.add_argument("--size", type=float, default=8.0, help="text size in pt (default 8)")
    args = ap.parse_args(argv)
    sys.stdout.write(to_mplstyle(load_style(args.style), args.font, args.size))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
